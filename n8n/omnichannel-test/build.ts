// Generates the executable OMNI v2 test workflows for n8n.
//
//   npx tsx n8n/omnichannel-test/generate.ts   (run from the repository root)
//
// The Code nodes embed a bundle of lib/omnichannel/master-runtime.ts because
// n8n Code nodes cannot import local files. Every workflow is inactive, has
// no credential, no HTTP node and no destination. The provider and the brain
// are fakes; the store is a test store passed between nodes.

import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { build } from "esbuild";

import { buildScenarioBundle } from "./scenarios";

const here = join(process.cwd(), "n8n", "omnichannel-test");

export const WORKFLOW_PREFIX = "OMNI v2 TEST";

type N8nNode = {
  parameters: Record<string, unknown>;
  id: string;
  name: string;
  type: string;
  typeVersion: number;
  position: [number, number];
};

type N8nWorkflow = {
  name: string;
  nodes: N8nNode[];
  connections: Record<string, { main: Array<Array<{ node: string; type: "main"; index: number }>> }>;
  pinData: Record<string, never>;
  active: false;
  settings: { executionOrder: "v1" };
  tags: [];
};

export type WorkflowBuild = {
  file: string;
  workflow: N8nWorkflow;
  steps: Record<string, string>;
};

export async function bundleRuntime() {
  const result = await build({
    entryPoints: [join(here, "src", "entry.ts")],
    bundle: true,
    format: "iife",
    globalName: "LexiaOmni",
    platform: "neutral",
    mainFields: ["module", "main"],
    target: "es2020",
    minify: true,
    legalComments: "none",
    write: false,
    banner: {
      js: "if (typeof structuredClone === 'undefined') { globalThis.structuredClone = (value) => JSON.parse(JSON.stringify(value)); }",
    },
  });
  const code = result.outputFiles[0]!.text;
  // Only JSON Schema identifiers may look like URLs: the public meta-schema
  // id and the fictitious .invalid contract ids. They are never fetched.
  const urls = code.match(/https?:\/\/[^"'\s]+/g) ?? [];
  const unexpected = urls.filter(
    (url) => url !== "https://json-schema.org/draft/2020-12/schema" && !url.startsWith("https://contracts.uselexia.invalid/"),
  );
  if (/\brequire\(/.test(code) || unexpected.length > 0) {
    throw new Error(`The runtime bundle must not require modules or reference URLs: ${unexpected.join(", ")}`);
  }
  return code;
}

function workflowBuilder(name: string, file: string, runtime: string) {
  const nodes: N8nNode[] = [];
  const connections: N8nWorkflow["connections"] = {};
  const steps: Record<string, string> = {};
  let counter = 0;
  const idPrefix = createHash("sha256").update(name).digest("hex").slice(0, 8);

  function add(node: Omit<N8nNode, "id" | "position">, step?: string) {
    counter += 1;
    nodes.push({
      ...node,
      id: `${idPrefix}-0000-4000-8000-${counter.toString(16).padStart(12, "0")}`,
      position: [counter * 240, 0],
    });
    if (step) steps[node.name] = step;
    return node.name;
  }

  const api = {
    trigger(nodeName = "Receive Envelope") {
      return add({
        parameters: { inputSource: "passthrough" },
        name: nodeName,
        type: "n8n-nodes-base.executeWorkflowTrigger",
        typeVersion: 1.1,
      });
    },
    manual(nodeName: string) {
      return add({ parameters: {}, name: nodeName, type: "n8n-nodes-base.manualTrigger", typeVersion: 1 });
    },
    code(nodeName: string, step: string, body: string, withRuntime = true) {
      const header = `// ${WORKFLOW_PREFIX} | ${step}\n// GENERATED by n8n/omnichannel-test/build.ts from lib/omnichannel/master-runtime.ts. Do not edit.\n`;
      return add(
        {
          parameters: { jsCode: `${header}${withRuntime ? `${runtime}\n` : ""}${body.trim()}\n` },
          name: nodeName,
          type: "n8n-nodes-base.code",
          typeVersion: 2,
        },
        step,
      );
    },
    ifNode(nodeName: string, expression: string) {
      return add({
        parameters: {
          conditions: {
            options: { caseSensitive: true, leftValue: "", typeValidation: "strict" },
            conditions: [
              {
                id: createHash("sha256").update(`${name}:${nodeName}`).digest("hex").slice(0, 32),
                leftValue: `={{ ${expression} }}`,
                rightValue: "",
                operator: { type: "boolean", operation: "true", singleValue: true },
              },
            ],
            combinator: "and",
          },
          options: {},
        },
        name: nodeName,
        type: "n8n-nodes-base.if",
        typeVersion: 2,
      });
    },
    exec(nodeName: string, target: string, step: string) {
      return add(
        {
          parameters: {
            source: "database",
            workflowId: { __rl: true, mode: "list", value: "", cachedResultName: `${WORKFLOW_PREFIX} - ${target}` },
            options: { waitForSubWorkflow: true },
          },
          name: nodeName,
          type: "n8n-nodes-base.executeWorkflow",
          typeVersion: 1.1,
        },
        step,
      );
    },
    loop(nodeName: string) {
      return add({
        parameters: { batchSize: 1, options: {} },
        name: nodeName,
        type: "n8n-nodes-base.splitInBatches",
        typeVersion: 3,
      });
    },
    connect(from: string, to: string, outputIndex = 0) {
      const entry = (connections[from] ??= { main: [] });
      while (entry.main.length <= outputIndex) entry.main.push([]);
      entry.main[outputIndex]!.push({ node: to, type: "main", index: 0 });
    },
    done(): WorkflowBuild {
      return {
        file,
        steps,
        workflow: {
          name: `${WORKFLOW_PREFIX} - ${name}`,
          nodes,
          connections,
          pinData: {},
          active: false,
          settings: { executionOrder: "v1" },
          tags: [],
        },
      };
    },
  };
  return api;
}

const READ = "const item = $input.first().json;";
const STASH = "const stash = $getWorkflowStaticData('global');";

export async function buildWorkflows(): Promise<WorkflowBuild[]> {
  const runtime = await bundleRuntime();
  const builds: WorkflowBuild[] = [];

  // Master: routes one envelope (event + test store) to the right path.
  {
    const w = workflowBuilder("Master", "master.json", runtime);
    const trigger = w.trigger();
    const route = w.code("Route Event", "route envelope by event type", `${READ}
const routed = LexiaOmni.routeEnvelope(item.store, item.event);
return [{ json: { store: item.store, ...routed } }];`);
    const isInbound = w.ifNode("Is Inbound?", "$json.route === 'inbound'");
    const ingress = w.exec("Run Ingress", "Ingress", "1-3 receive, persist, authorship, intervention");
    const isTick = w.ifNode("Is Buffer Tick?", "$json.route === 'buffer_tick'");
    const turn = w.exec("Run Conversation Turn", "Conversation Turn", "4-9 buffer, context, brain, apply, deliver");
    const isAutomation = w.ifNode("Is Automation?", "$json.route === 'automation'");
    const automation = w.exec("Run Automation", "Automation", "reminder/follow-up request");
    const automationAccepted = w.ifNode("Automation Accepted?", "$json.route === 'accepted'");
    const automationDelivery = w.exec("Run Delivery (Automation)", "Delivery", "8-9 per-action gate and fake provider");
    const automationNotSent = w.code("Automation Not Sent", "automation rejected or duplicate", `${READ}
return [{ json: item }];`, false);
    const isRecovery = w.ifNode("Is Recovery?", "$json.route === 'recovery'");
    const recovery = w.exec("Run Recovery", "Recovery", "reconcile or retry");
    const recoveryApplied = w.ifNode("Recovery Applied?", "$json.ok === true");
    const recoveryDelivery = w.exec("Run Delivery (Recovery)", "Delivery", "8-9 per-action gate and fake provider");
    const recoveryRejected = w.code("Recovery Rejected", "recovery refused", `${READ}
return [{ json: item }];`, false);
    const command = w.exec("Run State Command", "State Command", "platform command or policy");
    w.connect(trigger, route);
    w.connect(route, isInbound);
    w.connect(isInbound, ingress, 0);
    w.connect(isInbound, isTick, 1);
    w.connect(isTick, turn, 0);
    w.connect(isTick, isAutomation, 1);
    w.connect(isAutomation, automation, 0);
    w.connect(automation, automationAccepted);
    w.connect(automationAccepted, automationDelivery, 0);
    w.connect(automationAccepted, automationNotSent, 1);
    w.connect(isAutomation, isRecovery, 1);
    w.connect(isRecovery, recovery, 0);
    w.connect(recovery, recoveryApplied);
    w.connect(recoveryApplied, recoveryDelivery, 0);
    w.connect(recoveryApplied, recoveryRejected, 1);
    w.connect(isRecovery, command, 1);
    builds.push(w.done());
  }

  // Ingress: adapter, trusted scope, dedupe, persistence, authorship and an
  // immediate human intervention before any media processing.
  {
    const w = workflowBuilder("Ingress", "ingress.json", runtime);
    const trigger = w.trigger();
    const adapter = w.code("Adapter Ingress And Trusted Scope", "1 identify company, channel, account, conversation, author", `${READ}
const adapted = LexiaOmni.adapterIngress(item.store, item.raw);
return [{ json: { store: item.store, adapted } }];`);
    const accepted = w.ifNode("Accepted By Adapter?", "$json.adapted.route === 'accepted'");
    const ingest = w.code("Persist, Authorship And Intervention", "2-3 dedupe, persist before buffer, intervention first, pending during pauses", `${READ}
const ingested = LexiaOmni.ingest(item.store, { event: item.adapted.event, simulate_media_failure: item.adapted.simulate_media_failure });
return [{ json: { store: item.store, ingest: ingested } }];`);
    const rejected = w.code("Adapter Rejected", "unknown account or tenant mismatch", `${READ}
return [{ json: { store: item.store, ingest: { route: item.adapted.route, reason: item.adapted.reason } } }];`, false);
    w.connect(trigger, adapter);
    w.connect(adapter, accepted);
    w.connect(accepted, ingest, 0);
    w.connect(accepted, rejected, 1);
    builds.push(w.done());
  }

  // Conversation turn: buffer claim, context, brain, apply, delivery, finish.
  {
    const w = workflowBuilder("Conversation Turn", "conversation-turn.json", runtime);
    const trigger = w.trigger();
    const claim = w.code("Buffer Claim (Owner And Cutoff)", "4 debounce, owner by sequence, block check, cutoff", `${READ}
const claim = LexiaOmni.bufferTick(item.store, { conversation_key: item.conversation_key, candidate_seq: item.candidate_seq, at: item.at, execution_id: item.execution_id });
return [{ json: { ...item, claim } }];`);
    const claimed = w.ifNode("Batch Claimed?", "$json.claim.claimed === true");
    const context = w.code("History And Company Context", "5 scoped history and exact company context config", `${READ}
const prepared = LexiaOmni.prepareContext(item.store, { conversation_key: item.conversation_key, batch: item.claim.batch });
return [{ json: { ...item, prepared } }];`);
    const ready = w.ifNode("Context Ready?", "$json.prepared.route === 'ready'");
    const request = w.code("Build Brain Request", "6 lexia.brain.request.v1 with captured state and reprocess", `${READ}
${STASH}
const { request } = LexiaOmni.buildInvocation(item.store, { conversation_key: item.conversation_key, batch: item.claim.batch, context: item.prepared.context, messages: item.prepared.messages });
const script = LexiaOmni.takeBrainScript(item.store, { conversation_key: item.conversation_key });
const id_seed = LexiaOmni.reserveIdSeed(item.store);
// The private brain receives only its contract; the store stays here.
stash.turn = { store: item.store, conversation_key: item.conversation_key, at: item.at, execution_id: item.execution_id, invocation_id: request.invocation_id };
return [{ json: { brain_call: { request, script, id_seed } } }];`);
    const brain = w.exec("Call Private Brain (Fake)", "Brain Fake", "6 private brain and tools (fake)");
    const apply = w.code("Validate And Apply Brain Result", "7 validate, apply events with company policy, keep captured state", `${READ}
${STASH}
const turn = stash.turn;
const applied = LexiaOmni.applyResult(turn.store, { invocation_id: turn.invocation_id, result: item.brain_output.result, hooks: item.brain_output.hooks, at: turn.at });
return [{ json: { store: turn.store, invocation_id: turn.invocation_id, claimant: turn.execution_id, at: turn.at, applied } }];`);
    const deliver = w.exec("Deliver Plan", "Delivery", "8-9 per-action gate and fake provider");
    const finish = w.code("Finish Batch Or Supersede", "9 complete or supersede the batch for reprocessing", `${READ}
const finished = LexiaOmni.finishBatch(item.store, { invocation_id: item.invocation_id });
return [{ json: { store: item.store, turn: { invocation_id: item.invocation_id, finished, delivery: item.delivery } } }];`);
    const closeWithout = w.code("Close Batch Without Brain", "5 fail closed without context configuration", `${READ}
LexiaOmni.closeBatchWithoutBrain(item.store, { conversation_key: item.conversation_key, batch: item.claim.batch, reason: item.prepared.route });
return [{ json: { store: item.store, turn: { closed: item.prepared.route } } }];`);
    const notClaimed = w.code("Buffer Not Claimed", "4 another owner, window open, blocked or empty", `${READ}
return [{ json: { store: item.store, turn: { not_claimed: item.claim.reason } } }];`, false);
    w.connect(trigger, claim);
    w.connect(claim, claimed);
    w.connect(claimed, context, 0);
    w.connect(claimed, notClaimed, 1);
    w.connect(context, ready);
    w.connect(ready, request, 0);
    w.connect(ready, closeWithout, 1);
    w.connect(request, brain);
    w.connect(brain, apply);
    w.connect(apply, deliver);
    w.connect(deliver, finish);
    builds.push(w.done());
  }

  // Fake private brain: only the contract crosses this boundary.
  {
    const w = workflowBuilder("Brain Fake", "brain-fake.json", runtime);
    const trigger = w.trigger();
    const brain = w.code("Private Brain And Tools (Fake)", "6 fake brain: reply, handoff, simulated appointment tool", `${READ}
const brain_output = LexiaOmni.runFakeBrain(item.brain_call);
return [{ json: { brain_output } }];`);
    w.connect(trigger, brain);
    builds.push(w.done());
  }

  // Delivery loop: claim one action, send it to the fake provider, record it.
  {
    const w = workflowBuilder("Delivery", "delivery.json", runtime);
    const trigger = w.trigger();
    const claim = w.code("Claim Next Action (Gate)", "8 blocks, new messages, owner, duplicates, single confirmation", `${READ}
${STASH}
const base = item.store ? item : { ...stash.delivery, ...item };
const store = base.store;
const claim = LexiaOmni.claimNextAction(store, { invocation_id: base.invocation_id, claimant: base.claimant, at: base.at });
if (!claim.has_action) {
  stash.delivery = null;
  return [{ json: { has_action: false, store, invocation_id: base.invocation_id, reason: claim.reason } }];
}
stash.delivery = { store, invocation_id: base.invocation_id, claimant: base.claimant, at: base.at, action: claim.action, fencing_token: claim.fencing_token };
return [{ json: { provider_call: { action: claim.action, claimant: base.claimant, script: LexiaOmni.takeProviderScriptForAction(store, claim.action), id_seed: LexiaOmni.reserveIdSeed(store) } } }];`);
    const authorized = w.ifNode("Authorized To Send?", "$json.provider_call !== undefined");
    const provider = w.exec("Send Via Provider (Fake)", "Provider Send Fake", "8 fake provider records what it would receive");
    const record = w.code("Record Delivery Result", "9 record sent, failed or uncertain result", `${READ}
${STASH}
const d = stash.delivery;
const recorded = LexiaOmni.recordDelivery(d.store, { action: d.action, claimant: d.claimant, fencing_token: d.fencing_token, outcome: item.provider_output.outcome, provider_message_id: item.provider_output.provider_message_id, hooks: item.provider_output.hooks, received: item.provider_output.received, at: d.at });
stash.delivery = null;
return [{ json: { store: d.store, invocation_id: d.invocation_id, claimant: d.claimant, at: d.at, continue: recorded.continue } }];`);
    const more = w.ifNode("Continue Plan?", "$json.continue === true");
    const summary = w.code("Delivery Summary", "9 plan outcome", `${READ}
const outcome = LexiaOmni.planSummary(item.store, { invocation_id: item.invocation_id });
return [{ json: { store: item.store, invocation_id: item.invocation_id, claimant: item.claimant, at: item.at, delivery: outcome } }];`);
    w.connect(trigger, claim);
    w.connect(claim, authorized);
    w.connect(authorized, provider, 0);
    w.connect(authorized, summary, 1);
    w.connect(provider, record);
    w.connect(record, more);
    w.connect(more, claim, 0);
    w.connect(more, summary, 1);
    builds.push(w.done());
  }

  {
    const w = workflowBuilder("Provider Send Fake", "provider-send-fake.json", runtime);
    const trigger = w.trigger();
    const send = w.code("Fake Provider (No Network)", "8 fake provider, no network", `${READ}
const provider_output = LexiaOmni.runFakeProvider(item.provider_call);
return [{ json: { provider_output } }];`);
    w.connect(trigger, send);
    builds.push(w.done());
  }

  {
    const w = workflowBuilder("Automation", "automation.json", runtime);
    const trigger = w.trigger();
    const register = w.code("Register Automation Request", "reminder/follow-up through the same gate", `${READ}
const result = LexiaOmni.automationRequest(item.store, { request_id: item.request_id, conversation_key: item.conversation_key, kind: item.kind, source_ref: item.source_ref, text: item.text, at: item.at });
return [{ json: { store: item.store, route: result.route, reason: result.reason, invocation_id: result.invocation_id, claimant: item.claimant, at: item.at } }];`);
    w.connect(trigger, register);
    builds.push(w.done());
  }

  {
    const w = workflowBuilder("State Command", "state-command.json", runtime);
    const trigger = w.trigger();
    const apply = w.code("Apply State Command", "platform commands and admin-only policy", `${READ}
const result = LexiaOmni.stateCommand(item.store, item.command);
return [{ json: { store: item.store, command_result: result } }];`);
    w.connect(trigger, apply);
    builds.push(w.done());
  }

  {
    const w = workflowBuilder("Recovery", "recovery.json", runtime);
    const trigger = w.trigger();
    const recover = w.code("Reconcile Or Retry", "reconcile uncertain delivery or retry deterministic failure", `${READ}
const result = LexiaOmni.recovery(item.store, { operation: item.operation, conversation_key: item.conversation_key, action_id: item.action_id, status: item.status, provider_message_id: item.provider_message_id });
return [{ json: { store: item.store, ok: result.ok, reason: result.reason, invocation_id: result.invocation_id, claimant: item.claimant, at: item.at } }];`);
    w.connect(trigger, recover);
    builds.push(w.done());
  }

  // Scenario runner for the separate test environment: runs every synthetic
  // scenario through the master, one envelope per loop iteration.
  {
    const scenarios = buildScenarioBundle();
    const w = workflowBuilder("Scenario Runner", "scenario-runner.json", runtime);
    const manual = w.manual("Manual Trigger (Test Only)");
    const load = w.code("Load Synthetic Scenarios", "synthetic scenarios with two companies", `const scenarios = ${JSON.stringify(scenarios)};
const items = [];
for (const scenario of scenarios) {
  scenario.steps.forEach((step, index) => items.push({ json: { scenario_id: scenario.id, step_index: index, step, initial_store: index === 0 ? scenario.initial_store : null } }));
}
return items;`, false);
    const each = w.loop("Each Step");
    const attach = w.code("Attach Store And Fixtures", "load the scenario store and test fixtures", `${READ}
${STASH}
if (stash.scenario !== item.scenario_id) { stash.scenario = item.scenario_id; stash.store = item.initial_store; }
LexiaOmni.applyFixtures(stash.store, item.step.fixtures || []);
return [{ json: { store: stash.store, event: item.step.event, scenario_id: item.scenario_id, step_index: item.step_index, label: item.step.label } }];`);
    const master = w.exec("Run Master", "Master", "master envelope");
    const keep = w.code("Keep Store And Result", "keep the store between steps", `${READ}
${STASH}
stash.store = item.store;
stash.final = stash.final || {};
stash.final[stash.scenario] = item.store;
stash.results = stash.results || [];
const { store, ...result } = item;
stash.results.push({ scenario_id: stash.scenario, result });
return [{ json: { ok: true } }];`, false);
    const report = w.code("Scenario Report", "report", `${STASH}
return [{ json: { results: stash.results || [], final: stash.final || {} } }];`, false);
    w.connect(manual, load);
    w.connect(load, each);
    w.connect(each, report, 0);
    w.connect(each, attach, 1);
    w.connect(attach, master);
    w.connect(master, keep);
    w.connect(keep, each);
    builds.push(w.done());
  }

  return builds;
}

export function manifestFor(builds: WorkflowBuild[], runtimeHash: string) {
  return {
    generated_by: "n8n/omnichannel-test/build.ts",
    runtime_source: "lib/omnichannel/master-runtime.ts",
    runtime_sha256: runtimeHash,
    status: "inactive test workflows; import only into a separate authorized n8n test instance",
    workflows: builds.map((entry) => ({
      file: entry.file,
      name: entry.workflow.name,
      nodes: entry.workflow.nodes.map((node) => ({
        name: node.name,
        type: node.type,
        step: entry.steps[node.name] ?? null,
      })),
    })),
  };
}

export async function writeWorkflows() {
  const builds = await buildWorkflows();
  const runtime = await bundleRuntime();
  const outDir = join(here, "workflows");
  mkdirSync(outDir, { recursive: true });
  for (const entry of builds) {
    writeFileSync(join(outDir, entry.file), `${JSON.stringify(entry.workflow, null, 2)}\n`);
  }
  const hash = createHash("sha256").update(runtime).digest("hex");
  writeFileSync(join(outDir, "manifest.json"), `${JSON.stringify(manifestFor(builds, hash), null, 2)}\n`);
  console.log(`wrote ${builds.length} workflows, runtime ${Math.round(runtime.length / 1024)} KB`);
}

