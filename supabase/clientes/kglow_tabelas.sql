create table if not exists public.servicos_kglow (
  id                      bigint generated by default as identity primary key,
  nome                    text not null unique,
  nome_en                 text,
  nome_es                 text,
  aliases                 text[],
  categoria               text not null default 'outros',
  preco                   numeric,
  tipo_preco              text not null default 'fixo' check (tipo_preco in ('fixo','a_partir','sob_avaliacao','por_unidade')),
  requer_avaliacao        boolean not null default false,
  profissional            text,
  duracao_min             integer,
  descricao               text,
  preparo_e_cuidados      text,
  preparo_pre             text,
  cuidados_pos            text,
  observacoes             text,
  indicacao               text,
  contraindicacoes        text,
  sessoes                 text,
  variacao_preco          text,
  motivo_avaliacao        text,
  modo_preco              text not null default 'se_perguntar' check (modo_preco in ('se_perguntar','se_insistir','nunca')),
  proximo_passo           text not null default 'agendar' check (proximo_passo in ('agendar','avaliacao','equipe')),
  ativo                   boolean not null default true,
  precos_por_profissional jsonb,
  preco_retoque           numeric,
  dias_retoque            integer,
  moxie_servico_id        text,
  origem_item_id          uuid unique,
  criado_em               timestamptz not null default now()
);

create table if not exists public.info_kglow (
  chave     text primary key,
  valor     text not null,
  origem    text,
  ativo     boolean not null default true,
  criado_em timestamptz not null default now()
);

create table if not exists public.config_kglow (
  chave     text primary key,
  valor     text not null,
  origem    text,
  ativo     boolean not null default true,
  criado_em timestamptz not null default now()
);

create table if not exists public.profissionais_kglow (
  id               bigint generated by default as identity primary key,
  nome             text not null unique,
  especialidade    text,
  horario          jsonb,
  servicos         text[],
  agenda_google_id text,
  ativo            boolean not null default true,
  origem_item_id   uuid unique,
  criado_em        timestamptz not null default now()
);

create table if not exists public.promocoes_kglow (
  id                  bigint generated by default as identity primary key,
  campanha            text,
  nome                text not null,
  servico_ids         integer[] not null default '{}',
  preco_promocional   numeric,
  desconto_percentual numeric check (desconto_percentual is null or (desconto_percentual > 0 and desconto_percentual < 100)),
  profissional        text,
  condicao            text,
  brinde_pt           text,
  brinde_en           text,
  brinde_es           text,
  inicio              date not null default current_date,
  fim                 date,
  ate_acabar          boolean not null default false,
  anunciar_desde      date default current_date,
  apelidos            text[],
  publico             text not null default 'todos' check (publico in ('todos','novos','atuais')),
  observacoes         text,
  ativo               boolean not null default true,
  origem_item_id      uuid unique,
  criado_em           timestamptz not null default now(),
  check (fim is not null or ate_acabar)
);

